type LanguageContextValue = {
    language: Language;
    setLanguage: (language: Language) => void;
    t: (text: string) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
    const [language, setLanguageState] = useState<Language>("en");
    const [hasLoadedPreference, setHasLoadedPreference] = useState(false);

    useEffect(() => {
        const timeout = window.setTimeout(() => {
            const saved = window.localStorage.getItem("wedlock-language") as Language | null;
            if (saved === "en" || saved === "it" || saved === "es") setLanguageState(saved);
            setHasLoadedPreference(true);
        }, 0);
        return () => window.clearTimeout(timeout);
    }, []);

    useEffect(() => {
        document.documentElement.lang = language;
        if (hasLoadedPreference) window.localStorage.setItem("wedlock-language", language);
    }, [hasLoadedPreference, language]);

    useEffect(() => {
        const title = "WedLockStudio | Professional Video Editing Agency";
        const description = "Capture your moments with WedLockStudio. Professional video editing services.";
        const translate = (text: string) => language === "en" ? text : translations[language][text] ?? text;

        document.title = translate(title);
        document.querySelector('meta[name="description"]')?.setAttribute("content", translate(description));
        document.querySelector('meta[property="og:title"]')?.setAttribute("content", translate(title));
        document.querySelector('meta[property="og:description"]')?.setAttribute("content", translate(description));
        document.querySelector('meta[name="twitter:title"]')?.setAttribute("content", translate(title));
        document.querySelector('meta[name="twitter:description"]')?.setAttribute("content", translate(description));
    }, [language]);

    const value = useMemo<LanguageContextValue>(() => ({
        language,
        setLanguage: setLanguageState,
        t: (text) => language === "en" ? text : translations[language][text] ?? text,
    }), [language]);

    return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
    const context = useContext(LanguageContext);
    if (!context) throw new Error("useLanguage must be used within LanguageProvider");
    return context;
}
